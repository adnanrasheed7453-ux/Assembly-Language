                      .MODEL SMALL
.STACK 100H

.DATA
    SIDE1 DB 5
    SIDE2 DB 5
    SIDE3 DB 3

    NOT_TRI DB 'Not a triangle$'
    EQUILAT DB 'Equilateral$'
    ISOSCEL DB 'Isosceles$'
    SCALENE DB 'Scalene$'

.CODE
MAIN PROC
    MOV AX, @DATA
    MOV DS, AX

    MOV AL, SIDE1
    ADD AL, SIDE2
    CMP AL, SIDE3
    JLE NOT_TRIANGLE

    MOV AL, SIDE1
    ADD AL, SIDE3
    CMP AL, SIDE2
    JLE NOT_TRIANGLE

    MOV AL, SIDE2
    ADD AL, SIDE3
    CMP AL, SIDE1
    JLE NOT_TRIANGLE

    MOV AL, SIDE1
    CMP AL, SIDE2
    JNE CHECK_OTHER_EQUAL

    CMP AL, SIDE3
    JE EQUILATERAL_TRI
    JMP ISOSCELES_TRI

CHECK_OTHER_EQUAL:
    MOV AL, SIDE1
    CMP AL, SIDE3
    JE ISOSCELES_TRI

    MOV AL, SIDE2
    CMP AL, SIDE3
    JE ISOSCELES_TRI

    JMP SCALENE_TRI

NOT_TRIANGLE:
    LEA DX, NOT_TRI
    JMP DISPLAY_MESSAGE

EQUILATERAL_TRI:
    LEA DX, EQUILAT
    JMP DISPLAY_MESSAGE

ISOSCELES_TRI:
    LEA DX, ISOSCEL
    JMP DISPLAY_MESSAGE

SCALENE_TRI:
    LEA DX, SCALENE

DISPLAY_MESSAGE:
    MOV AH, 09H
    INT 21H

    MOV AH, 4CH
    INT 21H
MAIN ENDP
END MAIN