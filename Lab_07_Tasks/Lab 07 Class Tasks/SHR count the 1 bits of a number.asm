.MODEL SMALL
.STACK 100H

.DATA
NUM DB 10110111B
MSG DB 'Number of 1 bits: $'

.CODE
MAIN PROC

MOV AX, @DATA
MOV DS, AX

MOV AL, NUM
MOV BL, 0
MOV CX, 8

L1:
SHR AL, 1
JNC SKIP
INC BL

SKIP:
LOOP L1

; Display message
MOV AH, 09H
LEA DX, MSG
INT 21H

; Display count
MOV DL, BL
ADD DL, 00110000B
MOV AH, 02H
INT 21H

; Exit
MOV AH, 4CH
INT 21H

MAIN ENDP
END MAIN