.MODEL SMALL
.STACK 100H

.DATA
NUM DB 00000111B
MSG1 DB 'Even$'
MSG2 DB 'Odd$'

.CODE
MAIN PROC

MOV AX, @DATA
MOV DS, AX

MOV BL, NUM
ROR BL, 1

JC ODD

; Display Even
MOV AH, 09H
LEA DX, MSG1
INT 21H
JMP EXIT

ODD:
; Display Odd
MOV AH, 09H
LEA DX, MSG2
INT 21H

EXIT:
MOV AH, 4CH
INT 21H

MAIN ENDP
END MAIN